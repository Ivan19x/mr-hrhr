const PUBLIC_PATHS = ["/", "/institutional"];

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  const router = useRouter();
  const path = useRouterState({ select: (s) => s.location.pathname });

  // Offline caching is an app-only feature; the website always runs online.
  useEffect(() => {
    if (import.meta.env.PROD && isApp() && "serviceWorker" in navigator) {
      navigator.serviceWorker.register("/sw.js").catch(() => {});
    }
  }, []);

  // A level abandoned by refreshing or closing the tab is settled as a forfeit.
  useEffect(() => {
    if (!currentUserSync()) return;
    settleAbandonedAttempt().then((a) => {
      if (a) toast("Unfinished level counted as a forfeit", { description: "You left a live chart before finishing. Only finished attempts avoid the penalty." });
    });
  }, [path]);

  // Every page except the sign-in screen and the institutional page needs a local profile.
  useEffect(() => {
    if (PUBLIC_PATHS.includes(path)) return;
    if (!currentUserSync()) router.navigate({ to: "/", replace: true });
  }, [path, router]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <Toaster position="top-center" />
    </QueryClientProvider>
  );
}
